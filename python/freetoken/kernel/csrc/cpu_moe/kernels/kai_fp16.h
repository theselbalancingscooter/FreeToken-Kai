// Kai: fp16 -> fp32 for the per-block scales of the fork's GGUF Q4_0 / Q2_0 expert formats.
// Upstream dropped its copy from common.h when the NVFP4 row globals became fp32 (#739); the
// ggml block scales stay fp16 by format.
#pragma once

#include <cstdint>
#include <cstring>

namespace freetoken::cpu_moe {

inline float fp16_to_f32(uint16_t h) {
  const uint32_t sign = (uint32_t)(h & 0x8000u) << 16;
  uint32_t exp = (h >> 10) & 0x1Fu;
  uint32_t man = h & 0x3FFu;
  uint32_t f;
  if (exp == 0) {
    if (man == 0) {
      f = sign;
    } else {
      exp = 127 - 15 + 1;
      while ((man & 0x400u) == 0) {
        man <<= 1;
        --exp;
      }
      man &= 0x3FFu;
      f = sign | (exp << 23) | (man << 13);
    }
  } else if (exp == 0x1Fu) {
    f = sign | 0x7F800000u | (man << 13);
  } else {
    f = sign | ((exp + (127 - 15)) << 23) | (man << 13);
  }
  float out;
  std::memcpy(&out, &f, sizeof(out));
  return out;
}

}  // namespace freetoken::cpu_moe
